function sourceBasename(source: string): string {
  const withoutMarkupNoise = source
    .replace(/&amp;/gi, "&")
    .replace(/\\+$/g, "")
    .split(/[?#&]/, 1)[0];
  const rawBasename = withoutMarkupNoise.slice(withoutMarkupNoise.lastIndexOf("/") + 1);
  try {
    return decodeURIComponent(rawBasename);
  } catch {
    return rawBasename;
  }
}

/** Resolves a captured WordPress upload or generated thumbnail to an archived local asset. */
export function resolveCapturedLegacyAsset(source: string): string | null {
  const basename = sourceBasename(source);
  const candidates = [basename, basename.replace(/-\d{2,4}x\d{2,4}(?=\.[^.]+$)/i, "")];
  for (const candidate of candidates) {
    const originalName = capturedLegacyAssetByKey[candidate.toLowerCase()];
    if (originalName) return `/images/captured-legacy/source/${originalName}`;
  }
  return null;
}
