export function resolveCapturedLegacyAsset(source: string): string | null {
  const basename = sourceBasename(source);
  const candidates = [basename, basename.replace(/-\d{2,4}x\d{2,4}(?=\.[^.]+$)/i, "")];
  for (const candidate of candidates) {
    const originalName = capturedLegacyAssetByKey[candidate.toLowerCase()];
    if (originalName) return `/images/captured-legacy/source/${originalName}`;
  }
  return null;
}
